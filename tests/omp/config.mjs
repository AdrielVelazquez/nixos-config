import assert from 'node:assert/strict';
import { readFile, stat } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';

const f = JSON.parse(await readFile(process.argv[2], 'utf8'));
assert.equal(f.redditEnabled, true);
assert.equal(f.redditControlPlaneOrigin, 'https://llm-platform.snooguts.net');
assert.ok(f.redditSupport.startsWith('/nix/store/'));
await stat(f.redditSupport + '/quota.ts');
assert.ok(f.ocProviderPlugin.startsWith('file:///nix/store/'));
assert.equal(f.projectOptionsSource, f.ocProviderPlugin.slice('file://'.length) + '/src/options.mjs', 'OMP must use the selected corrected OpenCode package, not an independent old source');
for (const provider of ['ollama', 'llama.cpp', 'lm-studio', 'apple']) assert.ok(f.settings.disabledProviders.includes(provider), `${provider} must not be implicitly discovered`);
const { resolveOptions } = await import(pathToFileURL(f.projectOptionsSource).href);
assert.equal(resolveOptions(f.ocPluginOptions, {}).projectId, 'opencode-dev');
assert.equal(resolveOptions(f.ocPluginOptions, { LLM_PLATFORM_PROJECT_ID: 'fixture-override' }).projectId, 'fixture-override');
assert.equal(f.enabled, true);
assert.equal(f.razerEnabled, false);
assert.equal(f.piEnabled, true);
assert.equal(f.ocEnabled, true);
assert.equal(f.ocAlias, 'headroom wrap opencode');
assert.equal(f.settings.modelRoles.default, 'llmplatform/gpt-6.1-sol:high');
assert.equal(f.settings.modelRoles.plan, 'llmplatform/claude-sonnet-5-5:xhigh');
assert.equal(f.settings.modelRoles.tiny, 'llmplatform/gpt-6-luna:off');
assert.equal(f.settings.task.agentModelOverrides.scout, 'llmplatform/gpt-6.1-sol:low');
assert.equal(f.settings.task.agentModelOverrides.explore, 'llmplatform/gpt-6-luna:low');
assert.equal(f.settings.retry.modelFallback, false);
assert.equal(f.settings.providers.cacheWarming, 'off');
assert.equal(f.settings.task.completionProbe, false);
assert.equal(f.settings.memory.backend, 'off');
assert.equal(f.settings.advisor.enabled, false);
assert.equal(f.settings.eval.autoProvision, false);
assert.equal(f.settings.eval.tools.enabled, false);
assert.equal(f.settings.startup?.setupWizard, false);
assert.equal(f.settings.startup?.checkUpdate, false);
assert.equal(f.settings.theme, undefined, 'retain native OMP visuals');
assert.ok(f.settings.extensions.every(path => !/pi-visuals|zentui|opencode.*plugin|headroom\.ts/.test(path)));
assert.equal(f.mainConfigSymlink, false, 'native config.yml must remain writable');
assert.match(f.activation, /install -m 600/);
assert.match(f.activation, /\.omp\/agent\/config\.yml/);
assert.deepEqual(Object.keys(f.mcp.mcpServers).sort(), ['github', 'headroom', 'headroom_memory', 'serena']);
assert.equal(f.mcp.mcpServers.github.type, 'http');
assert.ok(f.mcp.mcpServers.github.headers.Authorization.startsWith('!/nix/store/'));
for (const name of ['headroom', 'headroom_memory', 'serena']) {
  assert.equal(typeof f.mcp.mcpServers[name].command, 'string');
  assert.deepEqual(f.mcp.mcpServers[name].args, []);
}
assert.equal(f.skills.length, 8); // two CE + six OpenSpec, plus collection root for Superpowers
for (const skill of f.skills) await stat(skill);
assert.equal(f.commands.length, 6);
assert.match(f.context, /native ask/);
assert.match(f.context, /Tuios reports turns\/approvals/);
const tuios = await readFile(f.tuiosFile, 'utf8');
assert.match(tuios, /agent-hook", "omp", "--integration", "1/);
assert.doesNotMatch(tuios, /__TUIOS_/);
assert.match(tuios, /ctx\?\.agent\?\.kind === "main"/);
const manifest = JSON.parse(await readFile(f.manifest, 'utf8'));
assert.equal(manifest.client, 'omp');
assert.equal(manifest.memory, true);
assert.equal(manifest.codeGraph, true);
assert.equal(manifest.tuningEnv.HEADROOM_EFFORT_ROUTER, '0');
assert.equal(manifest.tuningEnv.HEADROOM_VERBOSITY_AUTOTUNE, '0');
assert.ok(manifest.upstreamOrigins.every(origin => origin.startsWith('https://')));
assert.ok(!JSON.stringify(f).includes('project/fixture-user'));
console.log('PASS: native OMP config/role/MCP/skill/schema ownership, runtime-only auth, own transport, native visuals and three side-by-side commands');
